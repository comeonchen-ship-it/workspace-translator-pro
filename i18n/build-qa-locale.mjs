#!/usr/bin/env node
/**
 * Generates i18n/locales/qa.json — a pseudo-locale for QA.
 *
 *   node i18n/build-qa-locale.mjs
 *
 * Every English string is bracketed and padded ~40% longer:
 *
 *   "Save Configurations"  ->  "[Save Configurations·······]"
 *
 * This finds two classes of bug before any real translation exists:
 *
 *   1. Text WITHOUT brackets is a hard-coded string someone forgot to extract.
 *   2. Anything that overflows here will overflow in German (+30–40%).
 *
 * Padding is appended, never interleaved, so {placeholders} and HTML tags stay
 * intact. Dev-only; never shipped.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { ROOT_LOCALE } from './languages.js';

const HERE = dirname(fileURLToPath(import.meta.url));
const LOCALES = join(HERE, 'locales');

const EXPANSION = 0.4; // match German's worst case
const PAD_CHAR = '·';

const root = JSON.parse(readFileSync(join(LOCALES, `${ROOT_LOCALE}.json`), 'utf8'));

const out = {
  _meta: {
    code: 'qa',
    name: 'Pseudo-locale (QA)',
    basedOnEnVersion: root._meta?.version,
    completeness: 'full',
    reviewedBy: 'generated',
    updatedAt: new Date().toISOString().slice(0, 10),
    note: 'GENERATED by i18n/build-qa-locale.mjs — do not edit by hand, do not ship.',
  },
};

let count = 0;
for (const [key, value] of Object.entries(root)) {
  if (key === '_meta') continue;
  if (typeof value !== 'string') continue;

  // Pad based on visible length, ignoring markup and placeholders.
  const visible = value.replace(/<[^>]*>/g, '').replace(/\{\w+\}/g, '');
  const pad = PAD_CHAR.repeat(Math.max(3, Math.round(visible.length * EXPANSION)));

  // Trailing-space-only strings (e.g. sentence suffixes) would look broken bracketed.
  out[key] = value.trim() === '' ? value : `[${value}${pad}]`;
  count++;
}

const target = join(LOCALES, 'qa.json');
writeFileSync(target, JSON.stringify(out, null, 2) + '\n', 'utf8');

console.log(`\n✅ Wrote ${target}`);
console.log(`   ${count} strings, padded +${EXPANSION * 100}%, based on ${ROOT_LOCALE} v${root._meta?.version}\n`);
console.log('To use it, TEMPORARILY add this entry to i18n/languages.js:\n');
console.log("  { code: 'qa', endonym: '[QA]', english: 'Pseudo-locale', dir: 'ltr',");
console.log("    fallback: 'en', ui: true, target: false, lineHeight: 1.4, fontStack: 'latin' },\n");
console.log('Reload the extension, pick "[QA]" as the interface language, then walk every');
console.log('screen looking for (a) text with no brackets and (b) anything clipped or wrapped.');
console.log('Remove the entry before committing.\n');
